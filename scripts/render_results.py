"""Render docs/experiment_results.md from the machine-generated reports (no hand-copied numbers).

Usage (PowerShell):
    python scripts/render_results.py --dataset amazon_electronics

Every number in the output is read from reports/<dataset>/*.json and the
dataset manifest. Sections whose reports do not exist are marked
"NOT EXECUTED" instead of being filled in.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from review_intel.utils import DATA_DIR, PROJECT_ROOT, REPORTS_DIR, read_json, utc_now  # noqa: E402

NOT_EXECUTED = "_NOT EXECUTED: no report found. Run the command above; never fill this in by hand._"


def fmt(x, digits=4):
    return "-" if x is None else (f"{x:.{digits}f}" if isinstance(x, float) else str(x))


def metrics_table(rows: list[tuple[str, dict, dict | None, object, str]]) -> str:
    out = ["| Model | Accuracy | Macro-P | Macro-R | **Macro-F1** | F1 neg | F1 neu | F1 pos | ECE | Train time (s) | "
           "Latency median / p95 (ms) | Batch texts/s | Score type |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, m, lat, train_s, score_type in rows:
        pc = m["per_class"]
        lat = lat or {}
        ece = m.get("calibration", {}).get("ece")
        out.append(f"| {name} | {fmt(m['accuracy'])} | {fmt(m['macro_precision'])} | {fmt(m['macro_recall'])} | "
                   f"**{fmt(m['macro_f1'])}** | {fmt(pc['negative']['f1'])} | {fmt(pc['neutral']['f1'])} | "
                   f"{fmt(pc['positive']['f1'])} | {fmt(ece) if ece is not None else 'n/a'} | {fmt(train_s, 1)} | "
                   f"{fmt(lat.get('single_text_median_ms'), 2)} / {fmt(lat.get('single_text_p95_ms'), 2)} | "
                   f"{fmt(lat.get('batch_throughput_texts_per_s'), 0)} | {score_type} |")
    return "\n".join(out)


def confusion(m: dict) -> str:
    labels = m["confusion_matrix"]["labels"]
    lines = ["| true \\ predicted | " + " | ".join(labels) + " |", "|---" * (len(labels) + 1) + "|"]
    lines += [f"| {l} | " + " | ".join(str(v) for v in row) + " |"
              for l, row in zip(labels, m["confusion_matrix"]["matrix"])]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", default="amazon_electronics")
    parser.add_argument("--out", type=Path, default=PROJECT_ROOT / "docs" / "experiment_results.md")
    args = parser.parse_args()

    reports = REPORTS_DIR / args.dataset
    manifest_path = DATA_DIR / "processed" / args.dataset / "manifest.json"
    out = [f"# Experimental results: `{args.dataset}`", "",
           f"_Generated by `scripts/render_results.py` on {utc_now()} from `reports/{args.dataset}/`. "
           "Do not edit numbers by hand; rerun the script._", ""]

    out += ["## 1. Dataset", "", "Command: `python scripts/prepare_data.py --config configs/data/amazon_electronics.json`", ""]
    if manifest_path.exists():
        m = read_json(manifest_path)
        dl_path = DATA_DIR / "raw" / args.dataset / "download_manifest.json"
        if dl_path.exists():
            dl = read_json(dl_path)
            out += [f"- Source: {dl['dataset']}, category {dl['category']}; streamed "
                    f"{dl['total_review_lines_streamed']:,} review lines; uniform reservoir sample of "
                    f"{dl['sample_rows_written']:,} (seed {dl['seed']})."]
        out += [f"- Synthetic: **{m['is_synthetic']}**",
                f"- Input rows: {m['counts']['input_rows']:,}; after cleaning: {m['counts']['rows_after_cleaning']:,}",
                f"- Excluded: {m['counts']['excluded']}",
                f"- Split sizes: {m['split_sizes']} (strategy `{m['config']['split']['strategy']}`, seed "
                f"{m['config']['split']['seed']})",
                f"- Leakage checks: {m['leakage_checks']}", "",
                "| Class | All | Train | Val | Test |", "|---|---|---|---|---|"]
        for label in ("negative", "neutral", "positive"):
            cells = [f"{m['class_distribution'][s][label]['count']:,} ({m['class_distribution'][s][label]['percent']}%)"
                     for s in ("all", "train", "val", "test")]
            out.append(f"| {label} | " + " | ".join(cells) + " |")
    else:
        out.append(NOT_EXECUTED)

    out += ["", "## 2. Validation results (model selection)", "",
            "Commands: `python scripts/train_baselines.py ...`, `python scripts/train_transformer.py ...`, "
            "`python scripts/evaluate_models.py compare ...`", ""]
    val_dir = reports / "validation"
    val_reports = [read_json(p) for p in sorted(val_dir.glob("*.json"))] if val_dir.exists() else []
    if val_reports:
        val_reports.sort(key=lambda r: -r["validation"]["macro_f1"])
        out.append(metrics_table([(r["family"], r["validation"], r.get("latency"), r.get("training_time_seconds"),
                                   r["score_type"]) for r in val_reports]))
        for r in val_reports:
            out += ["", f"**{r['family']}** best parameters: `{r['best_params']}`"]
            if r.get("history"):
                out.append(f"Epoch history: `{r['history']}`")
            if r.get("grid"):
                out += ["", f"<details><summary>{r['family']}: full validation grid ({len(r['grid'])} runs)</summary>", "",
                        "| Features | Classifier params | Val macro-F1 | Val accuracy |", "|---|---|---|---|"]
                out += [f"| {g['features']} | `{g['classifier_params']}` | {g['val_macro_f1']} | {g['val_accuracy']} |"
                        for g in r["grid"]]
                out += ["", "</details>"]
    else:
        out.append(NOT_EXECUTED)
    families = {r["family"] for r in val_reports}
    if "distilbert" not in families:
        out += ["", "DistilBERT (Model C): " + NOT_EXECUTED]

    out += ["", "## 3. Model selection", ""]
    sel_path = reports / "model_selection.json"
    if sel_path.exists():
        sel = read_json(sel_path)
        out += [f"- Rule: {sel['selection_rule']}", f"- **Selected: `{sel['selected_family']}`** "
                f"(`{sel['model_version']}`), validation macro-F1 {sel['validation_macro_f1']}"]
    else:
        out.append(NOT_EXECUTED)

    out += ["", "## 4. Held-out test results", "",
            "Command: `python scripts/evaluate_models.py test --all ...` (run once, after selection)", ""]
    test_path = reports / "test_results.json"
    if test_path.exists():
        t = read_json(test_path)
        rows = []
        for family, r in t["results"].items():
            name = family if r["role"] == "selected" else f"{family} (post-selection)"
            rows.append((name, r["test"], r["latency_on_test_texts"], r.get("training_time_seconds"), r["score_type"]))
        out += [f"Test size: {t['test_size']:,}.", "", metrics_table(rows)]
        for family, r in t["results"].items():
            out += ["", f"### {family}: confusion matrix (test)", "", confusion(r["test"])]
            if "calibration" in r["test"]:
                c = r["test"]["calibration"]
                out.append(f"\nCalibration: ECE {c['ece']} (mean confidence {c['mean_confidence']}, accuracy {c['accuracy']})")
        env = t["environment"]
        lat_method = next(iter(t["results"].values()))["latency_on_test_texts"]["method"]
        out += ["", "### Environment", "", f"- Packages: `{env['packages']}`", f"- Platform: {env['platform']}",
                f"- GPU: {env.get('gpu', 'none')} (CUDA available: {env.get('cuda_available', False)})",
                "", "### Latency method", "", lat_method]
    else:
        out.append(NOT_EXECUTED)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
